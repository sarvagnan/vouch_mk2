"""Deterministic generated context kernel for coding agents."""

from __future__ import annotations

from vouch_mk2.checks.organizational import (
    check_acceptance_ownership,
    check_causal_red_history,
    check_independence,
    check_intent_validation,
    check_protective_closure_truthfulness,
)
from vouch_mk2.core.model import Snapshot
from vouch_mk2.projections.next_actions import next_actions


def agent_context(snapshot: Snapshot) -> str:
    actions = next_actions(snapshot)
    organizational = tuple(
        check(snapshot)
        for check in (
            check_acceptance_ownership,
            check_intent_validation,
            check_independence,
            check_causal_red_history,
            check_protective_closure_truthfulness,
        )
    )
    lines = [
        "<!-- Generated by vouch-mk2 — do not edit; regenerate with `vouch-mk2 emit-context` -->",
        "# Vouch context",
        "",
        (
            f"Revision {snapshot.revision}; {len(snapshot.units)} units; "
            f"{len(snapshot.deviations)} deviations; {len(snapshot.releases)} releases."
        ),
        "",
        "## Next actions",
        "",
    ]
    if actions:
        lines.extend(
            f"- `{action.command}` for {action.subject_kind}/{action.subject_id}: {action.reason}"
            for action in actions
        )
    else:
        lines.append("- none")
    lines.extend(("", "## Not mechanically provable", ""))
    lines.extend(
        f"- {result.check_id}: {result.detail}" for result in organizational
    )
    return "\n".join(lines) + "\n"
