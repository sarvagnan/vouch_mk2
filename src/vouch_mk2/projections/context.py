"""Deterministic generated context kernel for coding agents."""

from __future__ import annotations

from vouch_mk2.checks.organizational import (
    check_acceptance_ownership,
    check_causal_red_history,
    check_independence,
    check_intent_validation,
    check_protective_closure_truthfulness,
)
from vouch_mk2.checks.tier import check_tier_controls
from vouch_mk2.core.model import Snapshot
from vouch_mk2.projections.next_actions import next_actions


_MD_ESCAPED = frozenset("\\[]()*_`#<>")
_CANONICAL_PROGRAM_NAME = "vouch-mk2"


def escape_markdown(text: str) -> str:
    """Keep an identifier inside the Markdown fragment that contains it."""
    normalized = text.replace("\r", " ").replace("\n", " ")
    return "".join(
        f"\\{character}" if character in _MD_ESCAPED else character
        for character in normalized
    )


def agent_context(snapshot: Snapshot) -> str:
    actions = next_actions(snapshot)
    organizational = tuple(
        check(snapshot)
        for check in (
            check_acceptance_ownership,
            check_intent_validation,
            check_independence,
            check_causal_red_history,
            check_protective_closure_truthfulness,
            lambda current: check_tier_controls(
                current, legacy_projection=True
            ),
        )
    )
    header = (
        f"<!-- Generated by {_CANONICAL_PROGRAM_NAME} — do not edit; regenerate with "
        f"`{_CANONICAL_PROGRAM_NAME} generate` -->"
    )
    lines = [
        header,
        "# Vouch context",
        "",
        (
            f"Revision {snapshot.revision}; {len(snapshot.units)} units; "
            f"{len(snapshot.deviations)} deviations; {len(snapshot.releases)} releases; "
            f"assurance tier {snapshot.tier.value}."
        ),
        (
            "Event log head "
            + (f"`{snapshot.event_head}`." if snapshot.event_head else "GENESIS.")
        ),
        *(
            ()
            if snapshot.ci_policy.value == "ledger" and not snapshot.ci_exceptions
            else (
                f"CI policy {snapshot.ci_policy.value}; "
                f"{len(snapshot.ci_exceptions)} recorded open-unit exceptions.",
            )
        ),
        (
            "Acceptance packs: "
            f"{sum(bool(unit.acceptance_pack_digest) for unit in snapshot.units)} bound; "
            f"{sum(bool(unit.acceptance_pack_version) and not unit.acceptance_pack_digest for unit in snapshot.units)} label-only; "
            f"{sum(unit.pack_binding == 'late' for unit in snapshot.units)} bound late; "
            f"{sum(unit.pack_binding == 'rebound' for unit in snapshot.units)} rebound after publication."
        ),
        "",
        "## Pack rebound history",
        "",
        *(
            (
                f"- {escape_markdown(unit.ref().label())}: inventory "
                f"`{rebound.old_inventory_digest}` → `{rebound.new_inventory_digest}`; "
                f"test set `{rebound.old_test_set_digest}` → "
                f"`{rebound.new_test_set_digest}`; evidence head sequence "
                f"{rebound.evidence_head_sequence}; stated reason: "
                f"{escape_markdown(rebound.reason)}"
            )
            for unit in sorted(snapshot.units, key=lambda item: item.ref().label())
            for rebound in unit.rebound_history
        ),
        *(
            ("- none",)
            if not any(unit.rebound_history for unit in snapshot.units)
            else ()
        ),
        "",
        "## Next actions",
        "",
    ]
    if actions:
        lines.extend(
            f"- `{escape_markdown(action.command)}` for "
            f"{escape_markdown(action.subject_kind)}/{escape_markdown(action.subject_id)}: "
            f"{action.reason}"
            for action in actions
        )
    else:
        lines.append("- none")
    lines.extend(("", "## Not mechanically provable", ""))
    # D050: the ONE public assurance sentence, verbatim from docs/claim-boundary.md,
    # emitted into every context so no propagated surface can overstate it.
    lines.append(
        "Vouch checks only what artifacts can prove; where it cannot, it prints "
        "`NOT_CHECKED` rather than offering a button that fakes it."
    )
    lines.append("")
    lines.extend(
        f"- {result.check_id}: {result.detail}" for result in organizational
    )
    return "\n".join(lines) + "\n"
