from __future__ import annotations

import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "gen_commands_doc.py"


def _script_copy(tmp_path: Path) -> tuple[Path, Path, Path]:
    project = tmp_path / "project"
    scripts = project / "scripts"
    docs = project / "docs"
    scripts.mkdir(parents=True)
    docs.mkdir()
    script = scripts / SCRIPT.name
    script.write_bytes(SCRIPT.read_bytes())
    return project, script, docs / "commands.md"


def _run(project: Path, script: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(script), *arguments],
        cwd=project,
        capture_output=True,
        text=True,
        check=False,
    )


def test_render_is_deterministic(tmp_path: Path) -> None:
    project, script, commands = _script_copy(tmp_path)
    first_run = _run(project, script)
    assert first_run.returncode == 0, first_run.stdout + first_run.stderr
    first = commands.read_bytes()

    second_run = _run(project, script)
    assert second_run.returncode == 0, second_run.stdout + second_run.stderr
    assert commands.read_bytes() == first


def test_check_exit_codes_for_fresh_and_stale_file(tmp_path: Path) -> None:
    project, script, commands = _script_copy(tmp_path)
    generated = _run(project, script)
    assert generated.returncode == 0, generated.stdout + generated.stderr

    fresh = _run(project, script, "--check")
    assert fresh.returncode == 0, fresh.stdout + fresh.stderr

    commands.write_text("stale\n", encoding="utf-8")
    stale = _run(project, script, "--check")
    assert stale.returncode == 1
    assert len(stale.stderr.splitlines()) == 1


def test_generated_header_is_present(tmp_path: Path) -> None:
    project, script, commands = _script_copy(tmp_path)
    generated = _run(project, script)
    assert generated.returncode == 0, generated.stdout + generated.stderr
    assert commands.read_text(encoding="utf-8").startswith(
        "<!-- Generated by scripts/gen_commands_doc.py — do not edit; regenerate with "
        "`uv run python scripts/gen_commands_doc.py` -->\n"
    )
